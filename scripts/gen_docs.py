# ---- database schema ------------------------------------------------------------------------------
def gen_schema() -> str:
    import app.models  # noqa: F401  (registers every table)
    from app.db import Base

    def simple(col) -> str:
        t = col.type.__class__.__name__.lower()
        return {"uuid": "uuid", "string": "varchar", "text": "text", "integer": "int", "boolean": "bool", "datetime": "timestamptz",
                "json": "json", "float": "float", "date": "date", "largebinary": "bytes"}.get(t, t)

    out = ["erDiagram"]
    rels = []
    details = ""
    for t in sorted(Base.metadata.tables.values(), key=lambda t: t.name):
        out.append(f"    {t.name} {{")
        rows = []
        for c in t.columns:
            keys = ",".join(k for k, on in (("PK", c.primary_key), ("FK", bool(c.foreign_keys))) if on)
            out.append(f"        {simple(c)} {c.name}{(' ' + keys) if keys else ''}")
            fk = ", ".join(f"{f.column.table.name}.{f.column.name}" for f in c.foreign_keys)
            rows.append([f"`{c.name}`", simple(c), "yes" if c.nullable else "no", keys, fk])
            for f in c.foreign_keys:
                rels.append(f"    {f.column.table.name} ||--o{{ {t.name} : \"{c.name}\"")
        out.append("    }")
        idx = sorted(i.name for i in t.indexes if i.name)
        uniq = sorted("(" + ", ".join(c.name for c in u.columns) + ")" for u in t.constraints if u.__class__.__name__ == "UniqueConstraint")
        details += f"### `{t.name}`\n\n" + table(["Column", "Type", "Nullable", "Key", "References"], rows)
        if idx or uniq:
            details += "\n" + ("Indexes: " + ", ".join(f"`{i}`" for i in idx) + ". " if idx else "") + ("Unique: " + ", ".join(uniq) + "." if uniq else "") + "\n"
        details += "\n"
    out += sorted(set(rels))
    intro = (f"Tables from the SQLAlchemy models in `{rel(BACKEND / 'app' / 'models.py')}` (`Base.metadata`). The LangGraph "
             "checkpoint tables (`checkpoints`, `checkpoint_blobs`, `checkpoint_writes`, `checkpoint_migrations`) are created by "
             "LangGraph itself and aren't shown. Migrations are in `backend/alembic/versions/`.")
    return page("Database schema", intro, "## Diagram\n\n```mermaid\n" + "\n".join(out) + "\n```\n\n## Tables\n\n" + details)


# ---- API endpoints and OpenAPI ---------------------------------------------------------------------
def _permission(route) -> str:
    from app.security import current_principal

    found: list[str] = []

    def walk(dep) -> None:
        call = dep.call
        if getattr(call, "__name__", "") == "checker" and call.__closure__:
            for cell in call.__closure__:
                if isinstance(cell.cell_contents, str):
                    found.append(f"`{cell.cell_contents}`")
        elif call is current_principal:
            found.append("signed in")
        for sub in dep.dependencies:
            walk(sub)

    walk(route.dependant)
    perms = [f for f in found if f != "signed in"]
    if perms:
        return ", ".join(dict.fromkeys(perms))
    if found:
        return "any signed-in user (further checks in the handler)"
    return "checked in the handler, or public"


def gen_api(app) -> str:
    from fastapi.routing import APIRoute

    rows = []
    for r in app.routes:
        if not isinstance(r, APIRoute) or not r.path.startswith("/api"):
            continue
        fn = r.endpoint
        src = inspect.getsourcefile(fn)
        line = inspect.getsourcelines(fn)[1]
        doc = (inspect.getdoc(fn) or "").split("\n")[0]
        for m in sorted(r.methods):
            rows.append([m, f"`{r.path}`", _permission(r), f"`{rel(src)}: {fn.__name__}()` (line {line})", doc])
    intro = ("Every API endpoint with the permission it requires, read from the FastAPI routes and their `require(...)` "
             "dependencies. Endpoints marked *checked in the handler* do their own check (integration keys, department "
             "permissions, first-run setup). The full machine-readable spec is [openapi.json](../../api/openapi.json).")
    return page("API endpoints", intro, table(["Method", "Path", "Permission", "Handler", "Summary"], rows))


# ---- CLI ------------------------------------------------------------------------------------------
def gen_cli() -> str:
    from app.cli import build_parser

    parser = build_parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help for c in sub._choices_actions}
    body = ""
    for name, p in sub.choices.items():
        opts = [[", ".join(f"`{o}`" for o in a.option_strings), "yes" if a.required else "no", a.help or ""]
                for a in p._actions if a.option_strings and a.dest != "help"]
        body += f"## `{name}`\n\n{helps.get(name, '')}\n\n```bash\ndocker exec -it careflow-api-1 python -m app.cli {name}"
        body += "".join(f" {a.option_strings[0]} ..." for a in p._actions if a.option_strings and a.required) + "\n```\n\n"
        body += (table(["Option", "Required", "What it does"], opts) if opts else "No options.\n") + "\n"
    intro = (f"Administration commands, from `{rel(BACKEND / 'app' / 'cli.py')}: build_parser()`. Run them in the API container "
             "(as shown) or, outside Docker, from the `backend` folder with `python -m app.cli ...`.")
    return page("CLI commands", intro, body)


# ---- HL7 and connectors ---------------------------------------------------------------------------
def gen_hl7() -> str:
    from app.integrations import hl7
    from app.integrations.service import CONNECTOR_EVENTS, SUPPORTED

    # Put a distinct marker in each HL7 position, parse the message with CareFlow's own parser, and see where each
    # marker lands. The mapping below is therefore what the code really does, not what someone remembers.
    sample = "\r".join([
        "MSH|^~\\&|HIS|H|CAREFLOW|H|20260101010101||ADT^A01|CTRL1|P|2.5",
        "EVN|A01|20260102020202",
        "PID|1||PID3MRN^^^H^MR||PID5FAMILY^PID5GIVEN^PID5MIDDLE||19800101|F",
        "|".join(["PV1", "1", "PV12CLASS", "PV131WARD^PV132ROOM^PV133BED", "", "", "",
                  "D1^PV172FAMILY^PV173GIVEN^^^PV176PREFIX"] + [""] * 11 + ["PV1191VISIT", "", *([""] * 23), "20260103030303", "20260104040404"]),
        "IN1|1|PLAN|PAYER|IN14PAYER|||||||||||IN115PLAN",
    ])
    f = hl7.patient_fields(hl7.parse(sample))
    where = {"PID3MRN": "PID-3.1 (prefers the repetition typed `MR`)", "PID5": "PID-5 (given, middle, family)", "PV131WARD": "PV1-3.1",
             "PV133BED": "PV1-3.3 (falls back to PV1-3.2 room)", "PV17": "PV1-7 (prefix or `Dr.`, given, family)", "IN14PAYER": "IN1-4.1",
             "PV1191VISIT": "PV1-19.1", "PV12CLASS": "PV1-2.1", "2026-01-03": "PV1-44 (falls back to EVN-2, then MSH-7)", "2026-01-04": "PV1-45"}
    rows = []
    for name, value in vars(f).items():
        if name == "extra":
            continue
        text = str(value)
        src = next((v for k, v in where.items() if k in text), "derived (see payment type rules below)" if name == "payer_type" else "—")
        rows.append([f"`{name}`", src, f"`{text}`"])
    body = "## Patient fields read from ADT messages\n\n"
    body += ("Found by parsing a sample message with CareFlow's own parser (`app/integrations/hl7.py: patient_fields()`), "
             "so this table always matches the code.\n\n")
    body += table(["CareFlow field", "HL7 position", "Value parsed from the sample"], rows)
    body += ("\n## Payment type rules\n\n- **government** if the payer (IN1-4), plan type (IN1-15) or financial class (PV1-20) contains "
             "any of: " + ", ".join(f"`{h}`" for h in hl7.GOVERNMENT_HINTS) + "\n- **cashless** if there is an IN1 segment with a payer and "
             "PV1-20 isn't `SELF`, `SP` or `CASH`\n- **self_pay** otherwise\n")
    body += "\n## Supported HL7 message types\n\n" + "\n".join(f"- `{t}`" for t in sorted(SUPPORTED)) + "\n"
    body += "\nAny other type is answered with `AR` (rejected).\n\n## JSON connector events\n\n"
    rows = [[f"`{sys_}`", f"`{ev}`", d] for sys_, evs in CONNECTOR_EVENTS.items() for ev, d in evs.items()]
    body += table(["System (`/api/integrations/{system}/events`)", "Event", "What it means"], rows)
    intro = (f"How CareFlow reads hospital-system messages, from `{rel(BACKEND / 'app' / 'integrations' / 'hl7.py')}` and "
             f"`{rel(BACKEND / 'app' / 'integrations' / 'service.py')}` (`SUPPORTED`, `CONNECTOR_EVENTS`).")
    return page("HL7 and connector mappings", intro, body)


# ---- driver ---------------------------------------------------------------------------------------
def build() -> dict[Path, str]:
    from app.main import create_app

    app = create_app()
    files = {
        OUT / "environment-variables.md": gen_env(),
        OUT / "roles-and-permissions.md": gen_roles(),
        OUT / "action-catalog.md": gen_actions(),
        OUT / "staff-actions.md": gen_staff_actions(),
        OUT / "blocker-kinds.md": gen_blockers(),
        OUT / "event-types.md": gen_events(),
        OUT / "agent-graph.md": gen_graph(),
        OUT / "database-schema.md": gen_schema(),
        OUT / "api-endpoints.md": gen_api(app),
        OUT / "cli.md": gen_cli(),
        OUT / "hl7-mapping.md": gen_hl7(),
        OPENAPI: json.dumps(app.openapi(), indent=2, ensure_ascii=False) + "\n",
    }
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="don't write; exit 1 if any generated file is out of date")
    args = ap.parse_args()
    files = build()
    stale = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current is not None:
            current = current.replace("\r\n", "\n")
        if current != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if args.check:
        if stale:
            print("Out of date (run python scripts/gen_docs.py and commit):")
            print("\n".join(f"  {rel(p)}" for p in stale))
            return 1
        print(f"All {len(files)} generated files are up to date.")
        return 0
    print(f"Wrote {len(stale)} of {len(files)} files" + (": " + ", ".join(rel(p) for p in stale) if stale else " (no changes)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())

# ---- blocker kinds --------------------------------------------------------------------------------
def gen_blockers() -> str:
    labels = dict(re.findall(r"^\s+(\w+): \"([^\"]+)\",", (ROOT / "web" / "src" / "lib" / "format.ts").read_text(encoding="utf-8")
                             .split("export const KIND_LABEL", 1)[1].split("};", 1)[0], re.M))
    found: dict[str, dict] = {}
    checks = BACKEND / "app" / "agents" / "checks.py"
    tree = ast.parse(checks.read_text(encoding="utf-8"))
    for fn in [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name.startswith("check_")]:
        dept = fn.name.removeprefix("check_")
        for node in ast.walk(fn):
            if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "Issue" and node.args and isinstance(node.args[0], ast.Constant):
                k = node.args[0].value
                found.setdefault(k, {"depts": set(), "where": []})
                found[k]["depts"].add(dept)
                found[k]["where"].append(f"{rel(checks)}:{node.lineno}")
    graph = BACKEND / "app" / "agents" / "graph.py"
    for no, line in enumerate(graph.read_text(encoding="utf-8").splitlines(), start=1):
        if not re.search(r"kind\s*=\s*\"|\"kind\":\s*\"|kind = \"", line):
            continue  # only lines that set a blocker's kind, not comparisons or lists that mention one
        for k in re.findall(r"\"(waiting_on_dependency|action_not_applied|system_unavailable|no_record)\"", line):
            found.setdefault(k, {"depts": {"any"}, "where": []})
            found[k]["depts"].add("any")
            found[k]["where"].append(f"{rel(graph)}:{no}")
    rows = []
    for k in sorted(found):
        depts = sorted(found[k]["depts"] - {"any"}) or ["any department"]
        rows.append([f"`{k}`", labels.get(k, "*(no label in the web app; shown as the raw kind)*"), ", ".join(depts), "<br>".join(f"`{w}`" for w in found[k]["where"])])
    extra = sorted(set(labels) - set(found))
    body = table(["Kind", "Shown in the web app as", "Department", "Raised in"], rows)
    if extra:
        body += "\nLabels defined in the web app but never raised by the backend: " + ", ".join(f"`{e}`" for e in extra) + "\n"
    intro = (f"Every blocker kind the backend can raise (department checks in `{rel(checks)}` and graph nodes in `{rel(graph)}`), "
             "with the label from `web/src/lib/format.ts` (`KIND_LABEL`).")
    return page("Blocker kinds", intro, body)



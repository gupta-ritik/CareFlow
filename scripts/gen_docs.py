"""Generate CareFlow reference pages from the code, so the tables can't drift from what the code does.

    python scripts/gen_docs.py           # write docs/reference/generated/*.md and docs/api/openapi.json
    python scripts/gen_docs.py --check   # exit 1 if any generated file differs from what's committed (CI)

Every output starts with a "Generated by scripts/gen_docs.py — do not edit by hand" line. Only code defaults are
read (never your .env), so no secret can end up in the docs.
"""
from __future__ import annotations

import argparse
import ast
import inspect
import io
import json
import os
import re
import sys
import tokenize
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
OUT = ROOT / "docs" / "reference" / "generated"
OPENAPI = ROOT / "docs" / "api" / "openapi.json"
HEADER = "<!-- Generated by scripts/gen_docs.py — do not edit by hand -->\n"
NOTE = '!!! info "Generated from the code"\n    Generated by `scripts/gen_docs.py` — do not edit by hand. Run the script after changing the code.\n\n'

sys.path.insert(0, str(BACKEND))
os.environ.setdefault("CAREFLOW_LLM_MODE", "off")


def rel(path: str | Path) -> str:
    return Path(path).resolve().relative_to(ROOT).as_posix()


def table(headers: list[str], rows: list[list]) -> str:
    def cell(v) -> str:
        return str(v).replace("|", "\\|").replace("\n", " ") if v not in (None, "") else "—"

    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows]
    return "\n".join(lines) + "\n"


def page(title: str, intro: str, body: str) -> str:
    return f"{HEADER}# {title}\n\n{NOTE}{intro.strip()}\n\n{body.rstrip()}\n"


# ---- environment variables ------------------------------------------------------------------------
def _config_comments() -> tuple[dict[str, str], dict[str, str]]:
    """Inline comment per field, and the section heading (nearest comment block above) per field."""
    src = (BACKEND / "app" / "config.py").read_text(encoding="utf-8")
    inline: dict[str, str] = {}
    lines = src.splitlines()
    comments: dict[int, str] = {}
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        if tok.type == tokenize.COMMENT:
            comments[tok.start[0]] = tok.string.lstrip("#").strip()
    section: dict[str, str] = {}
    current = "General"
    field_re = re.compile(r"^    ([a-z_][a-z0-9_]*)\s*:")
    for no, line in enumerate(lines, start=1):
        stripped = line.strip()
        if stripped.startswith("#") and line.startswith("    #") and not line.startswith("     "):
            text = comments.get(no, "")
            if text and not text.startswith(("CAREFLOW_DATABASE_URL", "app.dburl", "Reads the repository-root")):
                current = re.split(r"[.(]", text)[0].strip() or current
            continue
        m = field_re.match(line)
        if m:
            name = m.group(1)
            section[name] = current
            if no in comments and not stripped.startswith("#"):
                inline[name] = comments[no]
            elif no < len(lines) and lines[no].startswith("        ") and (no + 1) in comments:
                inline[name] = comments[no + 1]  # field continued on the next line, comment at its end
    return inline, section


def gen_env() -> str:
    from app.config import Settings

    inline, section = _config_comments()
    groups: dict[str, list[list]] = defaultdict(list)
    for name, field in Settings.model_fields.items():
        env = f"CAREFLOW_{name.upper()}"
        if name == "database_url":
            env = "CAREFLOW_DATABASE_URL (or DATABASE_URL)"
        ann = field.annotation
        typ = str(ann) if getattr(ann, "__args__", None) else getattr(ann, "__name__", str(ann))
        typ = typ.replace("typing.", "").replace("NoneType", "None")
        default = field.default
        if isinstance(default, (list, dict)):
            default = json.dumps(default)
        elif default is None:
            default = "unset"
        desc = inline.get(name) or field.description or "(no description in config.py yet)"
        groups[section.get(name, "General")].append([f"`{env}`", f"`{typ}`", f"`{default}`", desc])
    body = ""
    for group, rows in groups.items():
        body += f"## {group}\n\n" + table(["Variable", "Type", "Default", "What it does"], rows) + "\n"
    intro = (f"Every backend setting, read from `{rel(BACKEND / 'app' / 'config.py')}` (class `Settings`). Set them in `.env` "
             "at the repository root or as environment variables. A blank value counts as unset. Defaults are the code "
             "defaults; `docker-compose.yml` and `render.yaml` override some of them.")
    return page("Environment variables", intro, body)


# ---- roles and permissions ------------------------------------------------------------------------
def gen_roles() -> str:
    from app.security import ROLE_DESCRIPTIONS, ROLE_PERMISSIONS

    roles = list(ROLE_PERMISSIONS)
    perms = sorted({p for ps in ROLE_PERMISSIONS.values() for p in ps})
    rows = [[f"`{p}`"] + ["✔" if p in ROLE_PERMISSIONS[r] else "" for r in roles] for p in perms]
    matrix = table(["Permission"] + roles, rows).replace("| — ", "|   ")
    desc = table(["Role", "Description"], [[r, ROLE_DESCRIPTIONS.get(r, "")] for r in roles])
    intro = f"Roles and their permissions, from `{rel(BACKEND / 'app' / 'security.py')}` (`ROLE_PERMISSIONS`, `ROLE_DESCRIPTIONS`)."
    return page("Roles and permissions", intro, "## Roles\n\n" + desc + "\n## Permission matrix\n\n" + matrix)


